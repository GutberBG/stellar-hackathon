@asynccontextmanager
async def lifespan(app: FastAPI) -> AsyncGenerator[None, None]:
    """Application lifespan context for initialization and cleanup."""
    logger.info("Initializing database tables...")
    await init_db()

    logger.info("Checking seed data...")
    await seed_initial_data()

    logger.info("Warming up Machine Learning Risk Engine...")
    get_risk_engine()

    yield
    logger.info("Shutting down Ayni Cacao backend...")


app = FastAPI(
    title=settings.APP_NAME,
    version=settings.APP_VERSION,
    description=(
        "Backend de Ayni Cacao: Plataforma de acopio transparente de cacao y factoring "
        "agrícola predictivo para cooperativas de Alto Beni y Palos Blancos, La Paz, Bolivia. "
        "Construido bajo Arquitectura Hexagonal y Clean Architecture."
    ),
    lifespan=lifespan,
    docs_url="/docs",
    redoc_url="/redoc",
)

# Open CORS configuration for future external frontend integration
app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.CORS_ORIGINS,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Centralized Domain Exception Handling
app.add_exception_handler(AyniException, ayni_exception_handler)

# Include API Router (/api/v1)
app.include_router(api_router)


@app.get("/", tags=["Health"])
async def root():
    return {
        "service": settings.APP_NAME,
        "version": settings.APP_VERSION,
        "environment": settings.APP_ENV,
        "status": "ONLINE",
        "docs": "/docs",
    }


@app.get("/health", tags=["Health"])
async def health_check():
    # Check ML model
    ml_loaded = False
    try:
        from app.api.v1.dependencies import get_risk_engine
        engine = get_risk_engine()
        ml_loaded = engine.model is not None
    except Exception:
        ml_loaded = False

    return {
        "status": "healthy" if ml_loaded else "degraded",
        "database": "connected",
        "ml_model_loaded": ml_loaded,
        "stellar_network": settings.STELLAR_NETWORK,
        "exchange_rate_bob": settings.EXCHANGE_RATE_USDC_BOB,
        "vaquita_pool_id": settings.VAQUITA_POOL_ID,
    }
